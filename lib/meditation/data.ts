/**
 * Returns today's featured technique for a given level, rotating daily
 */
export function getDailyTechnique(level: MeditationLevel, dateStr?: string): MeditationTechnique {
  const d = dateStr ? new Date(dateStr) : new Date();
  const dayOfYear = Math.floor((d.getTime() - new Date(d.getFullYear(), 0, 0).getTime()) / 86400000);
  const matching = TECHNIQUES.filter(t => t.level === level);
  const index = Math.abs(dayOfYear) % matching.length;
  return matching[index] || matching[0];
}
